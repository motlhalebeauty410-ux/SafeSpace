#============================================================
# Load Packages
#============================================================

library(tidyverse)
library(caret)

#============================================================
# Load PHQ-9 Dataset
#============================================================

phq_data <- read.csv(
  "data/Dataset_14-day_AA_depression_symptoms_mood_and_PHQ-9.csv",
  stringsAsFactors = FALSE
)

#============================================================
# Load Suicide Dataset
#============================================================

suicide_data <- read.csv(
  "data/Suicide_Detection.csv",
  stringsAsFactors = FALSE,
  fileEncoding = "UTF-8"
)

#############################################################
# PHQ-9 DATA PREPARATION
#############################################################

# Keep only PHQ-9 Questions

phq_data <- phq_data %>%
  select(
    phq1,
    phq2,
    phq3,
    phq4,
    phq5,
    phq6,
    phq7,
    phq8,
    phq9
  )

#############################################################
# Remove Missing Values
#############################################################

phq_data <- na.omit(phq_data)

#############################################################
# Calculate PHQ Total Score
#############################################################

phq_data$PHQ_Total <- rowSums(
  phq_data[,1:9]
)

#############################################################
# Create Severity Variable
#############################################################

phq_data$Severity <- cut(
  phq_data$PHQ_Total,
  breaks = c(-1,4,9,14,19,27),
  labels = c(
    "Minimal",
    "Mild",
    "Moderate",
    "Moderately Severe",
    "Severe"
  )
)

#############################################################
# Check Severity Distribution
#############################################################

table(phq_data$Severity)

#############################################################
# Check Missing Values
#############################################################

sum(is.na(phq_data))

#############################################################
# SUICIDE DATA PREPARATION
#############################################################

#############################################################
# Keep Required Variables
#############################################################

suicide_data <- suicide_data %>%
  select(text,class)

#############################################################
# Remove Missing Values
#############################################################

suicide_data <- na.omit(suicide_data)

#############################################################
# Fix Encoding
#############################################################

suicide_data$text <- iconv(
  suicide_data$text,
  from = "",
  to = "UTF-8",
  sub = ""
)

suicide_data <- suicide_data[
  !is.na(suicide_data$text),
]

#############################################################
# Sample Dataset
#############################################################

set.seed(123)

suicide_data <- suicide_data[
  sample(
    nrow(suicide_data),
    5000
  ),
]

#############################################################
# Check Dataset Size
#############################################################

nrow(suicide_data)

#############################################################
# Check Missing Values
#############################################################

sum(is.na(suicide_data))

#############################################################
# Save Prepared Data
#############################################################

write.csv(
  phq_data,
  "data/phq_clean.csv",
  row.names = FALSE
)

write.csv(
  suicide_data,
  "data/suicide_clean.csv",
  row.names = FALSE
)

